import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { modalities } from "../data/ecvo-content.mjs";
import { renderPausedPage } from "./render-paused-page.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedNote = "<!-- This file is generated by scripts/generate-modality-pages.mjs. Edit data/ecvo-content.mjs instead. -->";
const routes = [...modalities.map(({ slug }) => slug), "modalidades"];
const output = renderPausedPage({ generatedNote });
const checkOnly = process.argv.includes("--check");
const failures = [];

for (const route of routes) {
  const directory = resolve(root, route);
  const target = resolve(directory, "index.html");
  if (checkOnly) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== output) failures.push(route);
    continue;
  }

  await mkdir(directory, { recursive: true });
  await writeFile(target, output);
}

if (failures.length) {
  throw new Error(`Páginas fora de sincronia: ${failures.join(", ")}. Execute: node scripts/generate-modality-pages.mjs`);
}

console.log(checkOnly ? "Validação concluída: páginas de treino temporárias sincronizadas." : "Geradas: páginas de treino com o aviso temporário.");
