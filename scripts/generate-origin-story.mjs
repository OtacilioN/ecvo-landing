async function main() {
  if (originStory.mentor.achievements.length !== 5) throw new Error("A trajetória deve preservar as cinco conquistas informadas.");
  const home = await readFile(homeTarget, "utf8");
  const startIndex = home.indexOf(homeStart);
  const endIndex = home.indexOf(homeEnd);
  if (startIndex < 0 || endIndex < 0 || endIndex < startIndex) throw new Error("Marcadores da origem não encontrados em index.html.");

  const expectedPage = renderPage();
  const expectedHome = `${home.slice(0, startIndex)}${renderHomeSection()}${home.slice(endIndex + homeEnd.length)}`;

  if (process.argv.includes("--check")) {
    const currentPage = await readFile(pageTarget, "utf8").catch(() => "");
    const failures = [];
    if (currentPage !== expectedPage) failures.push("historia-ecvo/index.html está desatualizado");
    if (home !== expectedHome) failures.push("index.html está desatualizado");
    if (failures.length) {
      console.error(failures.map((failure) => `- ${failure}`).join("\n"));
      process.exitCode = 1;
      return;
    }
    console.log("Validação concluída: história de origem e chamada da homepage sincronizadas.");
    return;
  }

  await mkdir(pageDirectory, { recursive: true });
  await writeFile(pageTarget, expectedPage);
  await writeFile(homeTarget, expectedHome);
  console.log("Gerados: página da história da ECVO e chamada da homepage.");
}

await main();
