import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { originStory } from "../data/origin-story.mjs";
import { renderPausedPage } from "./render-paused-page.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pageDirectory = resolve(root, "historia-ecvo");
const pageTarget = resolve(pageDirectory, "index.html");
const generatedNote = "<!-- This file is generated by scripts/generate-origin-story.mjs. Edit data/origin-story.mjs instead. -->";
const expectedPage = renderPausedPage({ generatedNote });

if (originStory.mentor.achievements.length !== 5) {
  throw new Error("A trajetória deve preservar as cinco conquistas informadas.");
}

if (process.argv.includes("--check")) {
  const currentPage = await readFile(pageTarget, "utf8").catch(() => "");
  if (currentPage !== expectedPage) {
    throw new Error("historia-ecvo/index.html está desatualizado. Execute: node scripts/generate-origin-story.mjs");
  }
  console.log("Validação concluída: história preservada na fonte e página temporária sincronizada.");
} else {
  await mkdir(pageDirectory, { recursive: true });
  await writeFile(pageTarget, expectedPage);
  console.log("Gerada: página temporária da história da ECVO.");
}
