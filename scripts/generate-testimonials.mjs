import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { testimonials } from "../data/testimonials.mjs";
import { renderPausedPage } from "./render-paused-page.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pageDirectory = resolve(root, "depoimentos-alunos");
const pageTarget = resolve(pageDirectory, "index.html");
const generatedNote = "<!-- This file is generated by scripts/generate-testimonials.mjs. Edit data/testimonials.mjs instead. -->";
const expectedPage = renderPausedPage({ generatedNote });
const featured = testimonials.filter((testimonial) => testimonial.featured);

if (featured.length === 0 || featured.length > 3) {
  throw new Error("A curadoria preservada deve conter entre um e três depoimentos em destaque.");
}

if (process.argv.includes("--check")) {
  const currentPage = await readFile(pageTarget, "utf8").catch(() => "");
  if (currentPage !== expectedPage) {
    throw new Error("depoimentos-alunos/index.html está desatualizado. Execute: node scripts/generate-testimonials.mjs");
  }
  console.log("Validação concluída: depoimentos preservados na fonte e página temporária sincronizada.");
} else {
  await mkdir(pageDirectory, { recursive: true });
  await writeFile(pageTarget, expectedPage);
  console.log("Gerada: página temporária dos depoimentos da ECVO.");
}
