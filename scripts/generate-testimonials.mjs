async function main() {
  if (!featured.length) throw new Error("Selecione ao menos um depoimento para a homepage.");
  if (featured.length > 3) throw new Error("A homepage deve manter no máximo três depoimentos em destaque.");
  if (new Set(featured.map((testimonial) => testimonial.featuredOrder)).size !== featured.length) {
    throw new Error("Cada depoimento em destaque deve ter uma ordem exclusiva.");
  }

  const home = await readFile(homeTarget, "utf8");
  const startIndex = home.indexOf(homeStart);
  const endIndex = home.indexOf(homeEnd);
  if (startIndex < 0 || endIndex < 0 || endIndex < startIndex) {
    throw new Error("Marcadores da seção de depoimentos não encontrados em index.html.");
  }

  const expectedPage = renderPage();
  const expectedHomeSection = renderHomeSection();
  const expectedHome = `${home.slice(0, startIndex)}${expectedHomeSection}${home.slice(endIndex + homeEnd.length)}`;

  if (process.argv.includes("--check")) {
    const currentPage = await readFile(pageTarget, "utf8").catch(() => "");
    const failures = [];
    if (currentPage !== expectedPage) failures.push("depoimentos-alunos/index.html está desatualizado");
    if (home !== expectedHome) failures.push("index.html está desatualizado");
    if (failures.length) {
      console.error(failures.map((failure) => `- ${failure}`).join("\n"));
      process.exitCode = 1;
      return;
    }
    console.log(`Validação concluída: ${testimonials.length} depoimentos e ${featured.length} destaques sincronizados.`);
    return;
  }

  await mkdir(pageDirectory, { recursive: true });
  await writeFile(pageTarget, expectedPage);
  await writeFile(homeTarget, expectedHome);
  console.log(`Gerados: página com ${testimonials.length} depoimentos e homepage com ${featured.length} destaques.`);
}

await main();
