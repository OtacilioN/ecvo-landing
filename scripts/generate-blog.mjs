async function expectedFiles() {
  const home = await readFile(homeTarget, "utf8");
  const startIndex = home.indexOf(homeStart);
  const endIndex = home.indexOf(homeEnd);
  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    throw new Error("Marcadores do blog na homepage não foram encontrados.");
  }

  const nextHome = `${home.slice(0, startIndex)}${renderHomeSection(featuredBlogPost)}${home.slice(endIndex + homeEnd.length)}`;
  return [
    [homeTarget, nextHome],
    [resolve(blogDirectory, "index.html"), renderBlogIndex(blogPosts)],
    ...blogPosts.map((post) => [resolve(blogDirectory, post.slug, "index.html"), renderPost(post)]),
  ];
}

const files = await expectedFiles();

if (checkMode) {
  const mismatches = [];
  for (const [target, expected] of files) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== expected) mismatches.push(target.replace(`${root}/`, ""));
  }
  if (mismatches.length) {
    console.error(`Arquivos de blog fora de sincronia: ${mismatches.join(", ")}`);
    process.exitCode = 1;
  } else {
    console.log(`Blog validado: ${blogPosts.length} conteúdo publicado e chamada da homepage sincronizada.`);
  }
} else {
  for (const [target, contents] of files) {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, contents);
  }
  console.log(`Blog gerado: ${blogPosts.length} conteúdo publicado e chamada da homepage atualizada.`);
}
