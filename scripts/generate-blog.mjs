function renderBlock(block) {
  if (block.type === "p") return `<p>${block.html}</p>`;
  if (block.type === "list") return `<ul>${block.items.map((item) => `<li>${escapeHtml(item)}</li>`).join("")}</ul>`;
  if (block.type === "cadence") return `<div class="article-cadence">${block.items.map((item) => `<p>${escapeHtml(item)}</p>`).join("")}</div>`;
  if (block.type === "closing") return `<p class="article-closing">${block.html}</p>`;
  throw new Error(`Bloco de artigo desconhecido: ${block.type}`);
}

