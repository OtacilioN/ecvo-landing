import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { renderPausedPage } from "./render-paused-page.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedNote = "<!-- This file is generated by scripts/generate-paused-pages.mjs. -->";
const outputs = [
  ["index.html", renderPausedPage({ generatedNote, indexable: true })],
  ["404.html", renderPausedPage({ generatedNote })],
  ["wellhub-joao-pessoa/index.html", renderPausedPage({ generatedNote })],
  ["totalpass-joao-pessoa/index.html", renderPausedPage({ generatedNote })],
];

const checkOnly = process.argv.includes("--check");
const failures = [];

for (const [relativePath, output] of outputs) {
  const target = resolve(root, relativePath);
  if (checkOnly) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== output) failures.push(relativePath);
    continue;
  }

  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, output);
}

if (failures.length) {
  throw new Error(`Páginas fora de sincronia: ${failures.join(", ")}. Execute: node scripts/generate-paused-pages.mjs`);
}

console.log(checkOnly ? "Validação concluída: páginas temporárias sincronizadas." : "Geradas: páginas temporárias da ECVO.");
